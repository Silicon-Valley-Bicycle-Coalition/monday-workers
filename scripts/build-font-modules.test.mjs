import { test } from 'node:test';
import assert from 'node:assert/strict';
import { TARGETS, renderFontModule } from './build-font-modules.mjs';

test('renders each face as an EMBEDDED_FONTS entry under a do-not-edit header', () => {
  const text = renderFontModule({
    source: '@fontsource/manrope@1.0.0',
    faces: [{ family: 'Manrope', weight: 500, subset: 'latin', unicodeRange: 'U+0000-00FF', base64: 'd09GMg==' }],
  });
  assert.match(text, /^\/\/ Generated by scripts\/build-font-modules\.mjs from @fontsource\/manrope@1\.0\.0\. Do not edit/);
  assert.match(text, /export const EMBEDDED_FONTS: readonly EmbeddedFont\[\] = \[/);
  assert.match(text, /family: 'Manrope',\n    weight: 500,\n    subset: 'latin',\n    unicodeRange: 'U\+0000-00FF',\n    woff2Base64:\n      'd09GMg==',/);
});

test('every target embeds a latin subset of each family it uses', () => {
  for (const target of TARGETS) {
    for (const [family, { subsets, weights }] of Object.entries(target.faces)) {
      assert.ok(subsets.includes('latin'), `${target.out} ${family}`);
      assert.ok(weights.length > 0, `${target.out} ${family}`);
    }
  }
});
