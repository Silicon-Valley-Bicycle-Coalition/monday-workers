import { test } from 'node:test';
import assert from 'node:assert/strict';
import { PACKAGES, TARGETS, faceId, renderFontModule } from './build-font-modules.mjs';

test('renders each face as an EMBEDDED_FONTS entry under a do-not-edit header', () => {
  const text = renderFontModule({
    source: '@fontsource-variable/nunito-sans@1.0.0',
    faces: [
      {
        id: 'nunito-sans-latin-wght-normal',
        family: 'Nunito Sans',
        weight: '200 1000',
        style: 'normal',
        subset: 'latin',
        unicodeRange: 'U+0000-00FF',
        base64: 'd09GMg==',
      },
    ],
  });
  assert.match(text, /^\/\/ Generated by scripts\/build-font-modules\.mjs from @fontsource-variable\/nunito-sans@1\.0\.0\. Do not edit/);
  assert.match(text, /family: 'Nunito Sans';/);
  assert.match(text, /export const EMBEDDED_FONTS: readonly EmbeddedFont\[\] = \[/);
  assert.match(
    text,
    /id: 'nunito-sans-latin-wght-normal',\n    family: 'Nunito Sans',\n    weight: '200 1000',\n    style: 'normal',\n    subset: 'latin',\n    unicodeRange: 'U\+0000-00FF',\n    woff2Base64:\n      'd09GMg==',/
  );
});

test('faceId follows the Fontsource file names for static and variable packages', () => {
  assert.equal(faceId(PACKAGES.Poppins, { subset: 'devanagari', weight: 600, style: 'normal' }), 'poppins-devanagari-600-normal');
  assert.equal(faceId(PACKAGES['Nunito Sans'], { subset: 'latin', style: 'italic' }), 'nunito-sans-latin-wght-italic');
});

test('every target sets its text in Nunito Sans, with a latin subset', () => {
  for (const target of TARGETS) {
    assert.ok(target.faces['Nunito Sans']?.subsets.includes('latin'), target.out);
    for (const [family, spec] of Object.entries(target.faces)) {
      assert.ok(PACKAGES[family], `${target.out} ${family}`);
      assert.ok((PACKAGES[family].variable ? spec.styles : spec.weights).length > 0, `${target.out} ${family}`);
    }
  }
});
